function levelFor(ageBand: AgeBand, youthAge: number): DrillLevel {
  if (ageBand === "Senior") return "Senior Amateur";
  if (ageBand === "U14-U16" || youthAge >= 13) return "Youth U13-16";
  if (ageBand === "U6-U8" || youthAge <= 8) return "Grassroots";
  return "Youth U9-12";
}

